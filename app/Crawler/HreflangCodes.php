    public static function isValid(string $code): bool
    {
        if ($code === 'x-default') {
            return true;
        }

        $parts = explode('-', $code);
        $lang = $parts[0] ?? '';
        if (! in_array($lang, self::LANGUAGES, true)) {
            return false;
        }

        $i = 1;

        // Optional script subtag: 4 letters, Titlecase (e.g. Hans, Hant). Lenient.
        if (isset($parts[$i]) && preg_match('/^[A-Z][a-z]{3}$/', $parts[$i])) {
            $i++;
        }

        // Optional region: ISO 3166-1 alpha-2 (uppercase) or UN M49 numeric (3 digits).
        if (isset($parts[$i])) {
            $region = $parts[$i];
            if (! in_array($region, self::REGIONS, true) && ! preg_match('/^[0-9]{3}$/', $region)) {
                return false;
            }
            $i++;
        }

        // No leftover subtags after language[-script][-region].
        return ! isset($parts[$i]);
    }
